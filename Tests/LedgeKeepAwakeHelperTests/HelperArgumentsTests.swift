import Foundation
import Testing

@testable import LedgeKeepAwakeHelper

/// What launchd hands the daemon, and what it refuses to start without.
@Suite("The daemon's arguments")
struct HelperArgumentsTests {

    private let requirement = #"anchor apple generic and identifier "com.egemert.ledge""#

    private func parse(_ arguments: String...) throws -> HelperArguments {
        try HelperArguments.parse(["/path/to/LedgeKeepAwakeHelper"] + arguments)
    }

    @Test("The client identifier and the requirement come off the command line")
    func parses() throws {
        let parsed = try parse("--client", "com.egemert.ledge", "--requirement", requirement)
        #expect(parsed.clientIdentifier == "com.egemert.ledge")
        #expect(parsed.requirement == requirement)
    }

    @Test("The label is the client identifier with the service's own suffix")
    func label() throws {
        // It has to match the launchd plist exactly: it is the Mach service
        // name as well as the job label, and the two builds differ only here.
        #expect(try parse("--client", "com.egemert.ledge", "--requirement", requirement)
            .label == "com.egemert.ledge.keepawake")
        #expect(try parse("--client", "com.egemert.ledge.debug", "--requirement", requirement)
            .label == "com.egemert.ledge.debug.keepawake")
    }

    @Test("A daemon with no client to trust does not start")
    func clientRequired() {
        #expect(throws: HelperArguments.Problem.missing("--client")) {
            try parse("--requirement", requirement)
        }
    }

    @Test("A daemon with no requirement to check does not start")
    func requirementRequired() {
        // Starting anyway would mean a root process accepting connections from
        // anything on the Mac that knew the service name.
        #expect(throws: HelperArguments.Problem.missing("--requirement")) {
            try parse("--client", "com.egemert.ledge")
        }
    }

    @Test("A flag with nothing after it is a missing flag")
    func danglingFlag() {
        #expect(throws: HelperArguments.Problem.missing("--requirement")) {
            try parse("--client", "com.egemert.ledge", "--requirement")
        }
        #expect(throws: HelperArguments.Problem.missing("--client")) {
            try parse("--client", "--requirement", requirement)
        }
    }

    @Test("An identifier that is not one is refused")
    func malformedIdentifier() {
        for bad in ["com.egemert.ledge/../root", ".ledge", "ledge.", "com..ledge", "a b"] {
            #expect(throws: HelperArguments.Problem.malformedIdentifier(bad)) {
                try parse("--client", bad, "--requirement", requirement)
            }
        }
    }
}

/// Who is allowed to talk to a root process.
@Suite("The client requirement")
struct CodeSigningRequirementTests {

    @Test("A requirement the system can compile passes")
    func wellFormed() {
        #expect(CodeSigningRequirement.compiles(
            #"anchor apple generic and identifier "com.egemert.ledge" and certificate leaf[subject.OU] = "ABCDE12345""#))
    }

    @Test("The Developer ID shape compiles too")
    func developerIDShape() {
        // The release build's requirement names the two certificate fields
        // that tell a Developer ID signature from a development one. If this
        // ever stops compiling, release builds would refuse their own app.
        #expect(CodeSigningRequirement.compiles("""
            anchor apple generic \
            and certificate 1[field.1.2.840.113635.100.6.2.6] exists \
            and certificate leaf[field.1.2.840.113635.100.6.1.13] exists \
            and certificate leaf[subject.OU] = "ABCDE12345" \
            and identifier "com.egemert.ledge"
            """))
    }

    @Test("Anything the system cannot compile is refused before it is used")
    func malformed() {
        // Handing one of these to NSXPCListener is a documented fatal error,
        // so this check is the difference between a log line and a daemon that
        // traps every time launchd starts it.
        #expect(!CodeSigningRequirement.compiles(""))
        #expect(!CodeSigningRequirement.compiles("anchor apple generic and ((("))
        #expect(!CodeSigningRequirement.compiles("please let my friends in"))
    }

    @Test("No team identifier is written down anywhere in the daemon's source")
    func noTeamIsHardcoded() throws {
        // Ledge is signed by two identities with different teams: development
        // and Developer ID. A requirement compiled into the source would name
        // one of them, and the other build would then refuse its own app with
        // no way to tell from the outside why. The requirement is generated by
        // whatever signs the bundle and passed in at launch, and this test is
        // what keeps it that way.
        let root = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent().deletingLastPathComponent()
        let sources = root.appendingPathComponent("Sources", isDirectory: true)
        let files = FileManager.default.enumerator(at: sources, includingPropertiesForKeys: nil)?
            .compactMap { $0 as? URL }
            .filter { $0.pathExtension == "swift" } ?? []
        #expect(!files.isEmpty, "the source tree should have been found from \(#filePath)")

        for file in files {
            let text = try String(contentsOf: file, encoding: .utf8)
            #expect(!text.contains("4RNWG7PMY4"), "\(file.lastPathComponent) names a team")
            #expect(!text.contains("6R6MBBNV64"), "\(file.lastPathComponent) names a team")
        }
    }
}

/// When a daemon with nothing to do should stop existing.
@Suite("Idle exit")
struct IdleExitTests {

    @Test("A clean daemon nobody is talking to lets go")
    func exitsWhenIdle() {
        #expect(IdleExit.shouldExit(clean: true, connections: 0, idleFor: 60))
    }

    @Test("A daemon with a claim outstanding stays, however quiet it is")
    func staysWhileNotClean() {
        // launchd would start it again on demand, but nothing demands a
        // restore: the app that asked for the hold may be gone. Exiting here
        // is how a Mac is left unable to sleep.
        #expect(!IdleExit.shouldExit(clean: false, connections: 0, idleFor: 6_000))
    }

    @Test("A daemon with a client connected stays")
    func staysWhileConnected() {
        #expect(!IdleExit.shouldExit(clean: true, connections: 1, idleFor: 6_000))
    }

    @Test("A daemon that was busy a moment ago stays")
    func staysWhileRecentlyBusy() {
        #expect(!IdleExit.shouldExit(clean: true, connections: 0, idleFor: 59))
    }
}

/// Which boot this is.
@Suite("The boot session id")
struct BootSessionIDTests {

    @Test("The kernel's answer is stable within a boot")
    func stable() {
        let first = BootSessionID.current()
        #expect(!first.isEmpty)
        #expect(BootSessionID.current() == first,
                "two claims written minutes apart have to agree about the boot they are in")
    }
}
